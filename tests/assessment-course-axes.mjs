import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const ctx={window:{APP:{esc:String}},MutationObserver:class{observe(){}},document:{body:{}}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('public/course-roadmap.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('public/course-assessments.js','utf8'),ctx);
const a=ctx.window.CourseAssessments,r=ctx.window.CourseRoadmap;
const c={id:'pmp',chapters:[{outlineKey:'agile',ar:'محور رشيق معدل',en:'Customized agile',outlineOrder:0},{outlineKey:'custom-axis',ar:'ورشة المخاطر الخاصة',en:'Risk custom workshop',outlineOrder:1},{outlineKey:'intro',ar:'المقدمة',en:'Intro',outlineOrder:20}]};
ctx.window.LESSONS={p:[{ch:0,t:'Lesson',vimeo:'1'},{ch:1,t:'Special lesson',vimeo:'2'}]};
let axes=a.courseAxes('p',c);
assert.equal(axes[0].key,'agile');assert.equal(axes[0].en,'Customized agile');
const custom=axes.find(x=>x.key==='custom-axis');assert(custom);
const bank=[{id:'a',approach:'agile',meta:{primaryTopic:'scope'}},{id:'r',topic:'Risk',meta:{primaryTopic:'risk'}},{id:'c',topic:'Risk custom workshop'},{id:'d',meta:{primaryTopic:'custom-axis'}},{id:'p',phase:'planning'},{id:'b',domain:'business'}];
assert.deepEqual(Array.from(a.axisRows(bank,axes[0],c),q=>q.id),['a']);
assert.deepEqual(Array.from(a.axisRows(bank,custom,c),q=>q.id),['c','d'],'custom label does not sweep unrelated Risk questions');
assert.deepEqual(Array.from(a.axisRows(bank,axes.find(x=>x.key==='planning'),c),q=>q.id),['p']);
assert.deepEqual(Array.from(a.axisRows(bank,axes.find(x=>x.key==='business'),c),q=>q.id),['b']);
assert.equal(axes.find(x=>x.key==='planning').depth,1);
assert.equal(a.axisRows(bank,axes.find(x=>x.key==='ai'),c).length,0,'unknown axis has no fabricated questions');
r.renameChapter(c,'outline:agile','اسم جديد','New title');axes=a.courseAxes('p',c);
assert.equal(axes.find(x=>x.key==='agile').en,'New title');assert.equal(a.axisRows(bank,axes.find(x=>x.key==='agile'),c).length,1);
const other={id:'rmp',chapters:[{ar:'تخطيط مخاطر خاص',en:'Custom risk planning'},null,'Monitoring']};
const otherAxes=a.courseAxes('r',other);assert.equal(otherAxes.length,2);assert.equal(otherAxes[1].key,'source_2');
assert.deepEqual(Array.from(a.axisRows([{id:'ar',topic:'تخطيط مخاطر خاص'},{id:'en',topic:'Custom risk planning'},{id:'no',topic:'Risk'},{id:'idx',chapter_index:0}],otherAxes[0],other),q=>q.id),['ar','en','idx']);
const source=fs.readFileSync('public/course-assessments.js','utf8');
assert(source.includes("${key==='chapters'?'open':''}"));
assert(source.includes('data-practice-hub'));
console.log('PASS: course-authored axis order, renamed labels, nested phases, explicit metadata, stable IDs, bilingual exact custom mapping, disabled unknown axes, and non-PMP sparse chapter slots.');
